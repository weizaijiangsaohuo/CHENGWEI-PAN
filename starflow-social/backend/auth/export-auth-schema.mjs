// Export only from the disposable CI database. Never connect to a live instance.
import pg from 'pg';
import {betterAuth} from 'better-auth';
import {emailOTP} from 'better-auth/plugins';
import {getMigrations} from 'better-auth/db/migration';
import {authOptions} from './auth.mjs';
import {writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const database=new pg.Pool({host:'127.0.0.1',port:5432,user:'postgres',password:'ephemeral-ci-only',database:'starflow_auth_test'});
try {
 const existing=await database.query("SELECT tablename FROM pg_tables WHERE schemaname='public'");
 assert.equal(existing.rowCount,0,'export requires a fresh disposable database');
 const base=authOptions({database,origin:'https://schema-export.example.invalid',secret:'synthetic-schema-export-only-not-production-secret'});
 const auth=betterAuth({...base,plugins:[...base.plugins,emailOTP({disableSignUp:true,otpLength:6,expiresIn:300,allowedAttempts:3,storeOTP:'hashed',sendVerificationOTP:async()=>{throw Error('delivery disabled');}})]});
 const m=await getMigrations(auth.options);
 const sql=await m.compileMigrations();
 assert.match(sql,/create table/i);
 assert.doesNotMatch(sql,/\b(drop|truncate|delete from)\b/i);
 const tables=m.toBeCreated.map(t=>t.table);
 for(const n of ['user','session','account','verification','passkey','twoFactor','rateLimit'])assert.ok(tables.includes(n),n);
 for(const n of tables)assert.match(n,/^[a-zA-Z][a-zA-Z0-9_]*$/);
 const grants=tables.map(n=>'REVOKE ALL ON TABLE public."'+n+'" FROM PUBLIC;').join('\n');
 const out=['-- Generated by pinned Better Auth in an empty CI database; staging only.','BEGIN;','SET LOCAL search_path = public, pg_catalog;',sql,grants,'COMMIT;',''].join('\n');
 await writeFile('auth-schema-staging.sql',out,{flag:'wx'});
 console.log('STARFLOW_AUTH_SCHEMA_BEGIN\n'+out+'STARFLOW_AUTH_SCHEMA_END');
}finally{await database.end();}
